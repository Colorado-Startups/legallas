// Builds the room views (mcp/apps/views.ts) into views.generated.ts: each entry in view/ bundled with esbuild, with the
// chart kit it imports (src/scripts/viz/) and their stylesheets, into one self-contained HTML. The room's tokens
// (src/styles/tokens.css) go in first, less their font imports: a view loads nothing from anywhere.
//
//   node mcp/apps/build.ts            rewrites views.generated.ts
//   node mcp/apps/build.ts --check    exits 1 when it has drifted from its sources
//
// It needs npm packages (esbuild), so it runs in CI or a cloud lane, never on a laptop: the Views workflow
// (.github/workflows/mcp-views.yml) runs it on every change to the views or the chart kit and uploads the file it
// writes. build.test.ts runs the same check under npm test. Never edit views.generated.ts by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transform } from 'esbuild';

const HERE = import.meta.dirname;
const WEB = join(HERE, '..', '..');
export const GENERATED_FILE = join(HERE, 'views.generated.ts');
const TOKENS = join(WEB, 'src', 'styles', 'tokens.css');

/** Each view's entry and page title. views.ts names the resources; the keys here are its ViewName. */
export const ENTRIES = {
  overview: { file: join(HERE, 'view', 'overview.ts'), title: 'Case overview' },
  grid: { file: join(HERE, 'view', 'grid.ts'), title: 'Documents' },
} as const;

type View = keyof typeof ENTRIES;

/** The room's tokens without their @import lines (self-hosted fonts a view cannot load), minified. */
async function tokens(): Promise<string> {
  const css = readFileSync(TOKENS, 'utf8').replace(/^@import[^\n]*\n/gm, '');
  return (await transform(css, { loader: 'css', minify: true, legalComments: 'none' })).code.trim();
}

/** Text that can sit inside a <script> or <style> element without closing it. */
const inert = (code: string, tag: 'script' | 'style') => code.replace(new RegExp(`</(${tag})`, 'gi'), '<\\/$1');

/** Every view as its HTML page. Deterministic: the same sources and esbuild version give the same bytes. */
export async function buildViews(): Promise<Record<View, string>> {
  const result = await build({
    entryPoints: Object.fromEntries(Object.entries(ENTRIES).map(([name, entry]) => [name, entry.file])),
    bundle: true,
    write: false,
    outdir: join(HERE, 'out'),
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    charset: 'utf8',
    legalComments: 'eof',
    logLevel: 'silent',
  });
  const output = (name: string) => (result.outputFiles ?? []).find((file) => file.path.endsWith(`/${name}`))?.text.trim() ?? '';
  const base = await tokens();
  const pages = {} as Record<View, string>;
  for (const [view, entry] of Object.entries(ENTRIES) as [View, (typeof ENTRIES)[View]][]) {
    const js = output(`${view}.js`);
    if (!js) throw new Error(`esbuild wrote no ${view}.js`);
    const css = inert(base + output(`${view}.css`), 'style');
    pages[view] =
      '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
      '<meta name="viewport" content="width=device-width, initial-scale=1">' +
      `<title>${entry.title}</title><style>${css}</style></head>` +
      `<body><main id="app"></main><script>${inert(js, 'script')}</script></body></html>`;
  }
  return pages;
}

/** views.generated.ts for `pages`. */
export function renderGenerated(pages: Record<View, string>): string {
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    '// Generated by mcp/apps/build.ts from mcp/apps/view/ and src/scripts/viz/. Never edit by hand: run the Views workflow',
    '// (.github/workflows/mcp-views.yml) and commit the file it uploads.',
    `export const VIEW_HTML = ${JSON.stringify(pages, null, 2)} as const;`,
    '',
  ].join('\n');
}

async function main(argv: readonly string[]): Promise<number> {
  const pages = await buildViews();
  const expected = renderGenerated(pages);
  let current = '';
  try {
    current = readFileSync(GENERATED_FILE, 'utf8');
  } catch {
    // Missing: written below, or reported stale.
  }
  if (current === expected) {
    console.log('views.generated.ts is up to date.');
    return 0;
  }
  if (argv.includes('--check')) {
    console.error('views.generated.ts is out of date with mcp/apps/view/ or the chart kit. Run node mcp/apps/build.ts in CI (the Views workflow).');
    return 1;
  }
  writeFileSync(GENERATED_FILE, expected);
  console.log(`Wrote views.generated.ts (${Object.entries(pages).map(([view, page]) => `${view} ${Math.round(page.length / 1024)} KB`).join(', ')}).`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
