// Writes THIRD-PARTY-NOTICES for a release bundle (docs/licences/NOTICE-draft.md): the licence and NOTICE files of every
// package the bundle's code or assets came from, read from the bundlers' metafiles, then every licence file copied into
// the site (dist/pdfjs/). Fails, writing nothing, when a package has neither its own licence text nor a reviewed text in
// scripts/notices/. Never edit the output by hand; rebuild it.
//
//   LEGALLAS_METAFILE=meta/site.json npm run build
//   npx wrangler deploy -c wrangler.example.jsonc --dry-run --outdir out/web --metafile meta/web.json
//   npx wrangler deploy -c wrangler.mcp.example.jsonc --dry-run --outdir out/mcp --metafile meta/mcp.json
//   node scripts/notices.ts dist/THIRD-PARTY-NOTICES.txt dist meta/*.json
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** LICENSE, LICENCE.md, LICENSE-MIT, COPYING, NOTICE.txt and the like; never a code file such as notice.js. */
const LICENCE = /^(licen[cs]e|copying|notice)([-_][\w-]+)?(\.(md|txt|markdown))?$/i;
const WEB = path.resolve(import.meta.dirname, '..');

/** One package's section of the notices. */
export interface Notice {
  name: string;
  version: string;
  licence: string;
  texts: string[];
}

/** The package folder a module path belongs to (the folder after its last node_modules/), or null for our own code. */
export function packageDir(id: string, base = WEB): string | null {
  const clean = id.split('?')[0]!;
  // Bundler runtime helpers have virtual ids such as \0rolldown/runtime.js; they come from that package.
  if (clean.startsWith('\0')) return path.join(base, 'node_modules', clean.slice(1).split('/')[0]!);
  const at = clean.lastIndexOf('node_modules/');
  if (at < 0) return null;
  const [scope, name] = clean.slice(at + 'node_modules/'.length).split('/');
  return path.resolve(base, clean.slice(0, at + 'node_modules/'.length), scope!.startsWith('@') ? `${scope}/${name}` : scope!);
}

const files = (dir: string, match: RegExp) =>
  readdirSync(dir).filter((name) => match.test(name) && statSync(path.join(dir, name)).isFile()).sort();

/** A package's notice: its licence and NOTICE files, after any reviewed text kept in `extras` (scripts/notices/). */
export function noticeOf(dir: string, extras: string): Notice {
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')) as { name: string; version: string; license?: string };
  const extra = path.join(extras, `${pkg.name.replace('/', '__')}.txt`);
  const texts = [...(existsSync(extra) ? [extra] : []), ...files(dir, LICENCE).map((name) => path.join(dir, name))];
  return { name: pkg.name, version: pkg.version, licence: pkg.license ?? 'see text', texts: texts.map((file) => readFileSync(file, 'utf8').trim()).filter(Boolean) };
}

function* walk(dir: string): Generator<string> {
  for (const name of readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else yield full;
  }
}

/** The notices text for these metafiles and copied site. Throws, naming them, when packages have no licence text. */
export function buildNotices(dist: string, metafiles: string[], base = WEB, extras = path.join(WEB, 'scripts', 'notices')): string {
  const dirs = new Set<string>();
  for (const meta of metafiles) {
    const { inputs } = JSON.parse(readFileSync(meta, 'utf8')) as { inputs: Record<string, unknown> };
    for (const id of Object.keys(inputs)) {
      const dir = packageDir(id, base);
      if (dir) dirs.add(dir);
    }
  }
  const notices = new Map<string, Notice>();
  for (const dir of dirs) {
    const notice = noticeOf(dir, extras);
    notices.set(`${notice.name}@${notice.version}`, notice);
  }
  const bare = [...notices.keys()].filter((key) => notices.get(key)!.texts.length === 0);
  if (bare.length) throw new Error(`notices: no licence text for ${bare.sort().join(', ')}; add a reviewed one in scripts/notices/`);
  const copied = [...walk(dist)].filter((file) => /^licen[cs]e/i.test(path.basename(file)));
  const rule = '='.repeat(72);
  return [
    'THIRD-PARTY NOTICES',
    '',
    'This release of Legallas contains the third-party software and fonts below, each under its own licence.',
    'Generated by web/scripts/notices.ts from the build; not edited by hand.',
    ...[...notices.values()].sort((a, b) => a.name.localeCompare(b.name)).flatMap((n) => ['', rule, `${n.name} ${n.version} (${n.licence})`, rule, '', n.texts.join('\n\n')]),
    ...copied.flatMap((file) => ['', rule, `${path.relative(dist, file)}, copied with the files beside it`, rule, '', readFileSync(file, 'utf8').trim()]),
    '',
  ].join('\n');
}

if (import.meta.main) {
  const [out, dist, ...metafiles] = process.argv.slice(2);
  if (!out || !dist || metafiles.length === 0) {
    console.error('usage: node scripts/notices.ts <out-file> <dist-dir> <metafile>...');
    process.exit(2);
  }
  try {
    writeFileSync(out, buildNotices(path.resolve(dist), metafiles));
    console.log(`notices: wrote ${out}`);
  } catch (error) {
    console.error((error as Error).message);
    process.exit(1);
  }
}
