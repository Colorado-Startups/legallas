import Foundation

/// Assumptions for the year-by-year damages model: fund size, growth, fees, carry, discounting and terminal value.
public struct DamagesInputs: Sendable, Equatable {
    /// Fund assets under management at the start of year one.
    public let startingAUM: Decimal
    /// Yearly growth rate of the fund's assets under management.
    public let annualGrowthRate: Double
    /// Yearly management fee as a fraction of beginning-of-year assets.
    public let managementFeeRate: Double
    /// Fraction of the management fee that goes to the claimant.
    public let claimantFeeShare: Double
    /// Carried interest as a fraction of each year's asset growth.
    public let carryRate: Double
    /// Fraction of the carry allocated to partners.
    public let partnerAllocation: Double
    /// Fraction of the partner carry that goes to the claimant.
    public let claimantCarryShare: Double
    /// Yearly rate used to discount cash flows to present value.
    public let discountRate: Double
    /// Number of years modeled before the terminal value.
    public let horizonYears: Int
    /// Yearly growth rate of cash flow after the horizon, used for the terminal value.
    public let terminalGrowthRate: Double
    /// Flat amount of lost distributions added to the net present value.
    public let lostDistributions: Decimal
    /// Flat governance premium amount added to the net present value.
    public let governancePremium: Decimal

    /// Creates damages inputs; lost distributions and governance premium default to zero.
    public init(
        startingAUM: Decimal,
        annualGrowthRate: Double,
        managementFeeRate: Double,
        claimantFeeShare: Double,
        carryRate: Double,
        partnerAllocation: Double,
        claimantCarryShare: Double,
        discountRate: Double,
        horizonYears: Int,
        terminalGrowthRate: Double,
        lostDistributions: Decimal = 0,
        governancePremium: Decimal = 0
    ) {
        self.startingAUM = startingAUM
        self.annualGrowthRate = annualGrowthRate
        self.managementFeeRate = managementFeeRate
        self.claimantFeeShare = claimantFeeShare
        self.carryRate = carryRate
        self.partnerAllocation = partnerAllocation
        self.claimantCarryShare = claimantCarryShare
        self.discountRate = discountRate
        self.horizonYears = horizonYears
        self.terminalGrowthRate = terminalGrowthRate
        self.lostDistributions = lostDistributions
        self.governancePremium = governancePremium
    }
}

/// Result of a damages run: yearly rows, terminal value, adjustments, net present value and its trebled amount.
public struct DamagesComputation: Sendable, Equatable {

    /// One modeled year: assets, fees, carry, claimant cash flow and its discounted value.
    public struct YearRow: Sendable, Equatable {
        /// Year number, counting from 1.
        public let year: Int
        /// Assets under management at the start of the year.
        public let aumBegin: Decimal
        /// Assets under management at the end of the year.
        public let aumEnd: Decimal
        /// Management fee charged by the fund for the year.
        public let managementFee: Decimal
        /// Claimant's share of the management fee for the year.
        public let claimantManagementFee: Decimal
        /// Carried interest generated by the fund for the year.
        public let carry: Decimal
        /// Claimant's share of the carry for the year.
        public let claimantCarry: Decimal
        /// Total cash flow to the claimant for the year: fee share plus carry share.
        public let cashFlowToClaimant: Decimal
        /// Discount factor applied to the year's cash flow.
        public let discountFactor: Decimal
        /// Year's cash flow to the claimant discounted to present value.
        public let presentValue: Decimal
    }

    /// One row per modeled year.
    public let perYear: [YearRow]
    /// Terminal value of cash flows after the horizon, before discounting.
    public let terminalValueUndiscounted: Decimal
    /// Terminal value discounted to present value.
    public let terminalValuePresentValue: Decimal
    /// True when the terminal growth rate was at or above the discount rate, so the Gordon denominator rate was set to terminal growth plus 0.25% to keep the terminal value finite.
    public let terminalValueClamped: Bool
    /// Lost distributions amount added to the net present value.
    public let lostDistributionsAdjustment: Decimal
    /// Governance premium amount added to the net present value.
    public let governancePremiumAdjustment: Decimal
    /// Net present value: discounted yearly cash flows plus terminal value and the flat adjustments.
    public let npv: Decimal
    /// Net present value multiplied by three.
    public let trebledNPV: Decimal
}

/// Net present value outcome for one shift of the discount and growth rates.
public struct SensitivityCell: Sendable, Equatable {
    /// Shift applied to the discount rate, in basis points.
    public let discountRateDelta: Int
    /// Shift applied to the asset growth rate, in basis points.
    public let growthRateDelta: Int
    /// Net present value under the shifted rates.
    public let npv: Decimal
    /// Trebled net present value under the shifted rates.
    public let trebledNPV: Decimal
}

/// Computes damages from a set of inputs and runs sensitivity grids.
public enum DamagesCalculator {

    /// Runs the damages model for the given inputs and returns the yearly rows, terminal value, net present value and trebled value.
    public static func compute(_ inputs: DamagesInputs) -> DamagesComputation {
        let horizon = max(0, inputs.horizonYears)
        let growth = max(-0.99, inputs.annualGrowthRate)
        let r = inputs.discountRate
        let gT = inputs.terminalGrowthRate

        var rows: [DamagesComputation.YearRow] = []
        rows.reserveCapacity(horizon)

        var sumPV: Decimal = 0
        var lastCashFlow: Decimal = 0

        for t in 1...max(1, horizon) {
            if t > horizon { break }
            let aumBegin = inputs.startingAUM * decimalFactor(growth, power: t - 1)
            let aumEnd = inputs.startingAUM * decimalFactor(growth, power: t)
            let fundFee = aumBegin * Decimal(inputs.managementFeeRate)
            let claimantFee = fundFee * Decimal(inputs.claimantFeeShare)
            let yearGrowth = aumBegin * Decimal(growth)
            let fundCarry = yearGrowth * Decimal(inputs.carryRate)
            let partnerCarry = fundCarry * Decimal(inputs.partnerAllocation)
            let claimantCarry = partnerCarry * Decimal(inputs.claimantCarryShare)
            let cashFlow = claimantFee + claimantCarry
            let df = Decimal(Foundation.pow(1.0 + r, -Double(t)))
            let pv = cashFlow * df

            rows.append(.init(
                year: t,
                aumBegin: aumBegin,
                aumEnd: aumEnd,
                managementFee: fundFee,
                claimantManagementFee: claimantFee,
                carry: fundCarry,
                claimantCarry: claimantCarry,
                cashFlowToClaimant: cashFlow,
                discountFactor: df,
                presentValue: pv
            ))
            sumPV += pv
            lastCashFlow = cashFlow
        }

        var terminalClamped = false
        var terminalUndiscounted: Decimal = 0
        var terminalPV: Decimal = 0
        if horizon > 0 {
            let effectiveR: Double = {
                if gT >= r {
                    terminalClamped = true
                    return gT + 0.0025
                }
                return r
            }()
            let nextCashFlow = lastCashFlow * Decimal(1.0 + gT)
            let denom = Decimal(effectiveR - gT)
            if denom == 0 {
                terminalUndiscounted = 0
            } else {
                terminalUndiscounted = nextCashFlow / denom
            }
            let dfH = Decimal(Foundation.pow(1.0 + r, -Double(horizon)))
            terminalPV = terminalUndiscounted * dfH
        }

        let npv = sumPV + terminalPV + inputs.lostDistributions + inputs.governancePremium
        let trebled = npv * 3

        return DamagesComputation(
            perYear: rows,
            terminalValueUndiscounted: terminalUndiscounted,
            terminalValuePresentValue: terminalPV,
            terminalValueClamped: terminalClamped,
            lostDistributionsAdjustment: inputs.lostDistributions,
            governancePremiumAdjustment: inputs.governancePremium,
            npv: npv,
            trebledNPV: trebled
        )
    }

    /// Recomputes damages across every pairing of discount and growth rate shifts, given in basis points.
    public static func sensitivity(
        _ inputs: DamagesInputs,
        discountDeltas: [Int] = [-200, 0, 200],
        growthDeltas: [Int] = [-200, 0, 200]
    ) -> [SensitivityCell] {
        var cells: [SensitivityCell] = []
        cells.reserveCapacity(discountDeltas.count * growthDeltas.count)
        for dd in discountDeltas {
            for gd in growthDeltas {
                let shifted = DamagesInputs(
                    startingAUM: inputs.startingAUM,
                    annualGrowthRate: inputs.annualGrowthRate + Double(gd) / 10_000,
                    managementFeeRate: inputs.managementFeeRate,
                    claimantFeeShare: inputs.claimantFeeShare,
                    carryRate: inputs.carryRate,
                    partnerAllocation: inputs.partnerAllocation,
                    claimantCarryShare: inputs.claimantCarryShare,
                    discountRate: inputs.discountRate + Double(dd) / 10_000,
                    horizonYears: inputs.horizonYears,
                    terminalGrowthRate: inputs.terminalGrowthRate,
                    lostDistributions: inputs.lostDistributions,
                    governancePremium: inputs.governancePremium
                )
                let c = compute(shifted)
                cells.append(.init(
                    discountRateDelta: dd,
                    growthRateDelta: gd,
                    npv: c.npv,
                    trebledNPV: c.trebledNPV
                ))
            }
        }
        return cells
    }

    private static func decimalFactor(_ rate: Double, power exponent: Int) -> Decimal {
        Decimal(Foundation.pow(1.0 + rate, Double(exponent)))
    }
}
